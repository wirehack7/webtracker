// Writes sw.js into the built site with every file it needs offline: the app,
// its lazy chunks and workers, the manual with its pictures, the icons and the
// replayer page. Runs after the app and the replayer are built (pnpm build) and
// again in the deploy workflow after the tracking code is added, so the cache
// name changes whenever any served file does.
//
//   node scripts/service-worker.mjs [dist-dir]
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const dir = process.argv[2] ?? new URL('../packages/app/dist/', import.meta.url).pathname;
// Only for link previews on other sites; not needed in the app.
const SKIP = new Set(['sw.js', 'social-preview.png']);

const files = (await readdir(dir, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile())
  .map((entry) => join(entry.parentPath, entry.name).slice(dir.replace(/\/?$/, '/').length))
  .filter((file) => !SKIP.has(file))
  .sort();

const hash = createHash('sha256');
for (const file of files) hash.update(file).update('\0').update(await readFile(join(dir, file)));
const cache = `chiptrackr-${hash.digest('hex').slice(0, 12)}`;

// Folder pages are asked for by their folder name too.
const urls = files.map((f) => `./${f}`);
for (const page of files.filter((f) => f === 'index.html' || f.endsWith('/index.html'))) {
  urls.push(`./${page.slice(0, -'index.html'.length)}`);
}

const SOURCE = `// Generated by scripts/service-worker.mjs. Keeps the whole site in one cache,
// so chiptrackr runs offline after the first visit. A new version installs in
// the background and waits; the page offers a reload, which sends 'skip-waiting'.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(urls)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))));
});
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && /^(chiptrackr|webtracker)-/.test(k)).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== location.origin) return;
  // Pages and files come from the cache, so a page and its scripts are always from the same version.
  // Pages are matched without their query; the hash (#song=, #module=) never reaches the worker.
  const navigate = request.mode === 'navigate';
  event.respondWith(
    caches.match(request, { cacheName: CACHE, ignoreVary: true, ignoreSearch: navigate }).then((hit) =>
      hit ||
      fetch(request).catch((error) => {
        if (!navigate) throw error;
        return caches.match('./', { cacheName: CACHE }).then((app) => app || Promise.reject(error));
      })),
  );
});
`;

await writeFile(join(dir, 'sw.js'), SOURCE);
console.log(`sw.js: ${urls.length} files in cache ${cache}`);
